import org.bpy.electronics.mc6809.assembler.ui.AssemblerUiModule;
import org.eclipse.jface.resource.ImageDescriptor;
import org.eclipse.swt.graphics.Image;
import org.eclipse.ui.plugin.AbstractUIPlugin;

/**
 * Read and store icons. 
 * 
 * @author Patrick BRIAND
 *
 */
public class IconManager {

	/** Key for the constant icon */
	public static final String CONSTANT_ICON = "icons/define_obj.gif";
	/** Key for the data icon */
	public static final String DATA_ICON = "icons/variable_obj.gif";
	/** Key for the label icon */
	public static final String LABEL_ICON = "icons/label_obj.gif";
	/** Key for the macro icon */
	public static final String MACRO_ICON = "icons/macros_file.gif";
	
	/** For memorize the icons and avoid reloaded for each call */
	private Map<String,Image> iconCollection;
	/** For memorize the Image descriptor and avoid reloaded for each call */
	private Map<String,ImageDescriptor> imageDescriptorCollection;
	
	/** Instance on this class */
	private static IconManager instance;
	
	/** 
	 * Constructor of the class.
	 */
	public IconManager() {
		iconCollection = new HashMap<>();
		imageDescriptorCollection = new HashMap<>();
	}
	
	/** 
	 * Get instance on the class.
	 * 
	 * @return Instance on the icon manager
	 */
	public static IconManager getInstance() {
		if (instance == null) {
			instance = new IconManager();
		}
		return instance;
	}
	
	/**
	 * Get an icon.
	 * 
	 * @param key key of the icon
	 * @return icon object
	 */
	public Image getIcon(String key) {
		if (iconCollection.containsKey(key)) {
			return iconCollection.get(key);
		} else {
			ImageDescriptor mDescriptor = AbstractUIPlugin.imageDescriptorFromPlugin(AssemblerUiModule.PLUGIN_ID, key);
			Image image = mDescriptor.createImage();
			iconCollection.put(key, image);
			return image;
		}
	}
	
	/**
	 * Get the image descriptor of a key
	 * 
	 * @param key key of the icon
	 * @return image descriptor object
	 */
	public ImageDescriptor getImageDescriptor(String key) {
		if (imageDescriptorCollection.containsKey(key)) {
			return imageDescriptorCollection.get(key);
		} else {
			ImageDescriptor mDescriptor = AbstractUIPlugin.imageDescriptorFromPlugin(AssemblerUiModule.PLUGIN_ID, key);
			Image image = mDescriptor.createImage();
			iconCollection.put(key, image);
			return mDescriptor;
		}
	}
}
