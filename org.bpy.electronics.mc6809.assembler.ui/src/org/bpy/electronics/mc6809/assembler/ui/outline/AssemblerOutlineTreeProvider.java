/**
 * Customization of the default outline structure.
 *
 * See
 * https://www.eclipse.org/Xtext/documentation/310_eclipse_support.html#outline
 */
public class AssemblerOutlineTreeProvider extends DefaultOutlineTreeProvider {

	public class OutlineContainer extends AbstractOutlineNode {

		protected OutlineContainer(IOutlineNode parent, Image image, Object text, boolean isLeaf) {
			super(parent, image, text, isLeaf);
				// Nothing to do
			}
	}

	/** Reference on the serializer */
	@Inject @Extension private ISerializer serializer;

	/** current node in the outline view */
	private IOutlineNode macrosNode;
	/** current node in the outline view */
	private IOutlineNode labelsNode;
	/** current node in the outline view */
	private IOutlineNode equsNode;
	/** current node in the outline view */
	private IOutlineNode dataNode;
	
	@Override
	protected void _createChildren(DocumentRootNode parentNode, EObject modelElement) {

		IconManager iconManager = IconManager.getInstance();
		equsNode = new OutlineContainer(parentNode, iconManager.getIcon(IconManager.CONSTANT_ICON), "Constant", false);
		dataNode = new OutlineContainer(parentNode, iconManager.getIcon(IconManager.DATA_ICON), "Data definition", false);
		macrosNode = new OutlineContainer(parentNode, iconManager.getIcon(IconManager.MACRO_ICON), "Macros definition", false);
		labelsNode = new OutlineContainer(parentNode, iconManager.getIcon(IconManager.LABEL_ICON), "Labels definition", false);

		LinkedList<EObject> stack = new LinkedList<>();
		if (modelElement instanceof Model model) {

			stack.addAll(model.getSourceLines());
			while (!stack.isEmpty()) {

				EObject sourceLine = stack.pop();
				EObject line = ((SourceLine) sourceLine).getLineContent();

				manageSourceLine(line);
			}	
		}
	}

	/**
	 * Manage a source line in the assembly file
	 * 
	 * @param line reference on the line
	 */
	private void manageSourceLine(EObject line) {
		if (line instanceof LabelLine label) {
			manageLabelLine(label);

		} else if (line instanceof DirectiveLine directive) {
			manageDirectiveLine(directive);

		} else if (line instanceof SpecialFunctions specialFunction) {
			manageSpecialFunctions(specialFunction.getSpecialFuntion());

		} else if (line instanceof OtherKindOfInstructions otherInstruction) {
			manageOtherKingOfInstruction(otherInstruction);

		}
	}

	/**
	 * Manage a label line.
	 * 
	 * @param labelLine reference on the line
	 * @param label value of the label
	 * @param comment comment to display
	 */
	private void manageLabelElement(EObject labelLine, String label, String comment) {
		StringBuilder strBuilder = new StringBuilder(label);
		if (comment != null) {
			strBuilder.append(" : ");
			strBuilder.append(comment.substring(1));
		}
		
		IconManager iconManager = IconManager.getInstance();
		createEObjectNode(labelsNode, labelLine, iconManager.getIcon(IconManager.LABEL_ICON), strBuilder.toString(), true);
	}

	/**
	 * manage other kind of instruction, like call of macro 
	 * 
	 * @param line reference on the other kind line
	 */
	private void manageOtherKingOfInstruction(OtherKindOfInstructions line) {
		if (line.getLabel().getName() != null) {
			String labelName =  line.getLabel().getName().getValue();
			String comment = line.getComment();
			
			manageLabelElement(line, labelName, comment);
		}
	}

	/**
	 * manage a special function line 
	 * 
	 * @param macroDefinition reference on the special function line
	 */
	private void manageSpecialFunctions(MacroDefinition macroDefinition) {
			String macroName  = macroDefinition.getName().getValue();
			IconManager iconManager = IconManager.getInstance();
			EObjectNode currentMacroNode = createEObjectNode(macrosNode, macroDefinition, iconManager.getIcon(IconManager.MACRO_ICON), macroName, false);
			
			for (InstructionLine macroLine : macroDefinition.getInstructions()) {
				manageInstructionLine(currentMacroNode, macroLine);
			}
	}

	/**
	 * manage a label line (with out any instruction or directive)
	 * The icons is the first next element in the source 
	 * 
	 * @param line reference on the label line
	 */
	private void manageLabelLine(LabelLine line) {
		String label = getLabel(line);
		if (label != null) {
			String comment = line.getComment();
			manageLabelElement(line, label, comment);
		} 
	}

	/**
	 * Manage an directive line in the outline view

	 * @param line reference on the directive line
	 */
	private void manageDirectiveLine(DirectiveLine line) {

		String label = getLabel(line);
		if (label != null) {
			String comment = line.getComment();
			manageLabelElement(line, label, comment);
		}
		
		/* Manage Constant type instruction */
		if (line.getDirective() instanceof EquDirective equDirective) {
			String expressionRepresentation = serializer.serialize(equDirective.getOperand());
			manageConstantDeclaration(equDirective, "EQU" , label, expressionRepresentation);
		} else if (line.getDirective() instanceof SetDirective setDirective) {
			String expressionRepresentation = serializer.serialize(setDirective.getOperand());
			manageConstantDeclaration(setDirective, "SET" , label, expressionRepresentation);

		/* Manage data declaration */	
		} else if (line.getDirective() instanceof BszDirective bszDirective) {
			manageBszDirective(bszDirective);
		} else if (line.getDirective() instanceof FillDirective fillDirective) {
			manageFillDirective(fillDirective);
		} else if (line.getDirective() instanceof FcbDirective fcbDirective) {
			manageFcbDirective(fcbDirective);
		} else if (line.getDirective() instanceof FdbDirective fdbDirective) {
			manageFdbDirective(fdbDirective);
		} else if (line.getDirective() instanceof FccDirective fccDirective) {
			manageFccDirective(fccDirective);
		} else if (line.getDirective() instanceof RmbDirective rmbDirective) {
			manageRmbDirective(rmbDirective);
			
		}
	}

	/**
	 * Manage data of type RMB.
	 * 
	 * @param fillDirective reference on the directive
	 */
	private void manageRmbDirective(RmbDirective rmbDirective) {
		StringBuilder  strBuilder = new StringBuilder("Reseve ");
		
		if (rmbDirective.getOperand() != null) {
			strBuilder.append(serializer.serialize(rmbDirective.getOperand()));
			strBuilder.append(" memory bytes");
		}
		IconManager iconManager = IconManager.getInstance();
		createEObjectNode(dataNode, rmbDirective, iconManager.getIcon(IconManager.DATA_ICON), strBuilder.toString(), true);
	}

	/**
	 * Manage data of type FCC.
	 * 
	 * @param fillDirective reference on the directive
	 */
	private void manageFccDirective(FccDirective fccDirective) {
		StringBuilder  strBuilder = new StringBuilder("Force constant String ");
		if (fccDirective.getParameters() != null) {
			for (EObject parameter : fccDirective.getParameters()) {
				if (!strBuilder.isEmpty()) {
					strBuilder.append(",");
				}
				strBuilder.append(serializer.serialize(parameter));
			}
		}
		
		IconManager iconManager = IconManager.getInstance();
		createEObjectNode(dataNode, fccDirective, iconManager.getIcon(IconManager.CONSTANT_ICON), strBuilder.toString(), true);
	}


	/**
	 * Manage data of type FDB.
	 * 
	 * @param fillDirective reference on the directive
	 */
	private void manageFdbDirective(FdbDirective fdbDirective) {
		StringBuilder  strBuilder = new StringBuilder("Force constant Word ");
		if (fdbDirective.getOperand() != null) {
			strBuilder.append(serializer.serialize(fdbDirective.getOperand()));
		}	
		
		IconManager iconManager = IconManager.getInstance();
		createEObjectNode(dataNode, fdbDirective, iconManager.getIcon(IconManager.DATA_ICON), strBuilder.toString(), true);
	}

	/**
	 * Manage data of type FCB.
	 * 
	 * @param fillDirective reference on the directive
	 */
	private void manageFcbDirective(FcbDirective fcbDirective) {
		StringBuilder  strBuilder = new StringBuilder("Force constant Byte ");
		if (fcbDirective.getOperand() != null) {
			strBuilder.append(serializer.serialize(fcbDirective.getOperand()));
		}

		IconManager iconManager = IconManager.getInstance();
		createEObjectNode(dataNode, fcbDirective, iconManager.getIcon(IconManager.CONSTANT_ICON), strBuilder.toString(), true);
	}

	/**
	 * Manage data of type BSZ.
	 * 
	 * @param fillDirective reference on the directive
	 */
	private void manageBszDirective(BszDirective bszDirective) {
		StringBuilder  strBuilder = new StringBuilder("Set ");
		if (bszDirective.getOperand() != null) {
			strBuilder.append(serializer.serialize(bszDirective.getOperand()));
			strBuilder.append(" bytes to 0");
		}

		IconManager iconManager = IconManager.getInstance();
		createEObjectNode(dataNode, bszDirective, iconManager.getIcon(IconManager.DATA_ICON), strBuilder.toString(), true);
	}

	/**
	 * Manage data of type FILL.
	 * 
	 * @param fillDirective reference on the directive
	 */
	private void manageFillDirective(FillDirective fillDirective) {
		StringBuilder  strBuilder = new StringBuilder("Fill ");
		if (fillDirective.getNumber() != null) {
			strBuilder.append(serializer.serialize(fillDirective.getNumber()));
			strBuilder.append(" bytes with ");
			strBuilder.append(serializer.serialize(fillDirective.getValue()));
		}
	
		IconManager iconManager = IconManager.getInstance();
		createEObjectNode(dataNode, fillDirective, iconManager.getIcon(IconManager.DATA_ICON), strBuilder.toString(), true);
	}

	/**
	 * Create an outline entry for a an EQU or SET directive.
	 * 
	 * @param directive reference on the directive
	 * @param directiveName Name of the directive
	 * @param label Value of the label
	 * @param expression Expression of the directive
	 */
	private void manageConstantDeclaration(EObject directive, String directiveName, String label, String expression) {
		IconManager iconManager = IconManager.getInstance();
		createEObjectNode(equsNode, directive, iconManager.getIcon(IconManager.CONSTANT_ICON), label + " = " + expression, true);
	}

	/**
	 * Manage an instruction line in the outline view
	 * @param line reference on the instruction line
	 */
	private void manageInstructionLine(EObjectNode node, InstructionLine line) {
		IconManager iconManager = IconManager.getInstance();
		createEObjectNode(node, line, iconManager.getIcon(IconManager.MACRO_ICON), CommandUtil.getInstructionName(line.getInstruction()), true);
	}

	/** 
	 * Return name to display in the outline view
	 * @param line reference on the directive line
	 * @return label value, <b>null</b> if not defined
	 */
	private String getLabel(DirectiveLine line) {
		if (line.getLabel() != null && line.getLabel().getName() != null) {
			return line.getLabel().getName().getValue();
		} else {
			return null;
		}
	}

	/** 
	 * Return name to display in the outline view
	 * @param line reference on the label line
	 * @return label value, <b>null</b> if not defined
	 */
	private String getLabel(LabelLine line) {
		if (line.getLabel() != null && line.getLabel().getName() != null) {
			return line.getLabel().getName().getValue();
		} else {
			return null;
		}
	}
}
